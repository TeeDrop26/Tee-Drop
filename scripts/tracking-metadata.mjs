// Shared output contract for both the browser and the Apps Script receiver.
export const trackingScripts = '<script src="/tracking-config.js"></script><script src="/tracking-metadata.js"></script><script src="/tracking.js"></script>';
export function trackingOutputs({ registry, facilities, courses, areas, coursePages, outputs }) {
  const pages = { '/': { type: 'home', label: 'Course directory' }, '/indoor.html': { type: 'indoor', label: 'Indoor Golf' }, '/about.html': { type: 'about', label: 'About' } };
  for (const a of areas) pages[`/golf-courses/${a.slug}/`] = { type: 'area', label: a.name };
  for (const c of coursePages) {
    const r = registry.find(r => r.id === c.id);
    pages[`/courses/${r.slug}/`] = { type: 'course', courseId: r.id, label: r.name };
  }
  const courseKeys = Object.fromEntries(registry.map(r => [r.name + '\n' + r.city, r.id]));
  const allowed = {};
  const add = (page, id, action) => { (allowed[page] ||= []); const value = id + ':' + action; if (!allowed[page].includes(value)) allowed[page].push(value); };
  for (const r of registry) {
    const c = courses.find(c => c.name === r.name && c.city === r.city);
    add('/', r.id, c.bookingUrl.startsWith('tel:') ? 'phone' : c.bookingUrl.startsWith('mailto:') ? 'email' : c.rateInfo?.status === 'closed' ? 'course_updates' : c.bookingLabel ? 'course_info' : 'booking');
  }
  for (const f of facilities) add('/indoor.html', f.id, f.bookingUrl.startsWith('tel:') ? 'phone' : f.bookingUrl.startsWith('mailto:') ? 'email' : f.bookingLabel === 'online' ? 'booking' : 'course_info');
  for (const [file, html] of outputs) {
    if (!file.endsWith('.html')) continue;
    const page = '/' + file.replace(/index\.html$/, '');
    for (const match of html.matchAll(/<a\b[^>]*data-tracking-course="([^"]+)"[^>]*data-tracking-action="([^"]+)"[^>]*>/g)) add(page, match[1], match[2]);
  }
  const data = { pages, courseKeys, allowed, courses: Object.fromEntries(registry.map(r => [r.id, r.name])), facilities: Object.fromEntries(facilities.map(f => [f.id, f.name])) };
  return new Map([
    ['tracking-metadata.js', '// Generated by scripts/build-seo.mjs.\nwindow.TEE_DROP_TRACKING_METADATA = ' + JSON.stringify({pages, courseKeys}) + ';\n'],
    ['tracking/backend/Metadata.gs', '// Generated by scripts/build-seo.mjs.\nconst TRACKING_METADATA = ' + JSON.stringify(data, null, 2) + ';\n']
  ]);
}
